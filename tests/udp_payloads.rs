#[test]
fn service_probe_selection_matches_nmap_eligibility() {
    let entries = build_script::parse_service_probes(
        r"Exclude U:1-65535
Probe UDP First q|a#b\x7c\0\n\r\t\\|
rarity 9
ports 523,3483,5060-5061,65535
sslports 12345
Probe UDP Skip q|skip| no-payload
ports 523
Probe UDP SkipSuffix q|skip too| no-payloadX
ports 523
Probe TCP Reset q|tcp|
ports 523
Probe UDP NoPorts q|none|
sslports 523
Probe UDP Last q@final@
ports 0,53",
    )
    .unwrap();
    assert_eq!(entries.len(), 2);
    assert_eq!(entries[0].ports, [523, 3483, 5060, 5061, 65535]);
    assert_eq!(entries[0].payload, b"a#b|\0\n\r\t\\");
    assert_eq!(entries[1].ports, [0, 53]);
    assert_eq!(entries[1].payload, b"final");
}

