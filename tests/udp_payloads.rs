#[test]
fn every_port_matches_nmap_and_explicit_supplements() {
    use std::collections::{BTreeMap, BTreeSet};
    type Probes = BTreeMap<u16, BTreeSet<Vec<u8>>>;
    fn expand(entries: Vec<build_script::Entry>) -> Probes {
        let mut result = Probes::new();
        for entry in entries {
            for port in entry.ports {
                result
                    .entry(port)
                    .or_default()
                    .insert(entry.payload.clone());
            }
        }
        result
    }

    // This fixture is exported by the pinned Nmap executable's payload API,
    // not generated by our parser. See tests/nmap_reference.py to regenerate.
    let mut nmap = Probes::new();
    for line in include_str!("fixtures/nmap-udp-selection.tsv").lines() {
        if line.starts_with('#') {
            continue;
        }
        let (ports, hex) = line.split_once('\t').unwrap();
        let payload: Vec<u8> = (0..hex.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).unwrap())
            .collect();
        for spec in ports.split(',') {
            let (first, last) = spec.split_once('-').unwrap_or((spec, spec));
            for port in first.parse::<u16>().unwrap()..=last.parse().unwrap() {
                nmap.entry(port).or_default().insert(payload.clone());
            }
        }
    }
    assert_eq!(nmap.len(), 33_110);
    assert_eq!(nmap.values().map(BTreeSet::len).sum::<usize>(), 33_204);
    let services =
        expand(build_script::parse_service_probes(include_str!("../nmap-service-probes")).unwrap());
    let empty = BTreeSet::new();
    for port in 0..=u16::MAX {
        let reference = nmap.get(&port).unwrap_or(&empty);
        assert_eq!(
            services.get(&port).unwrap_or(&empty),
            reference,
            "Nmap selection udp/{port}"
        );
        let expected: BTreeSet<_> = reference
            .iter()
            .map(Vec::as_slice)
            .chain(
                supplemental_payloads::PROBES
                    .iter()
                    .filter(|(destination, _)| *destination == port)
                    .map(|(_, payload)| *payload),
            )
            .collect();
        let generated: BTreeSet<_> = payloads_for(port).iter().copied().collect();
        assert_eq!(generated, expected, "generated selection udp/{port}");
    }
}

fn contains(haystack: &[u8], needle: &[u8]) -> bool {
    haystack.windows(needle.len()).any(|w| w == needle)
}

#[test]
fn generated_lookup_matches_every_vendored_entry_and_gap() {
    use std::collections::BTreeMap;
    let mut entries =
        build_script::parse_service_probes(include_str!("../nmap-service-probes")).unwrap();
    entries.extend(
        supplemental_payloads::PROBES
            .iter()
            .map(|&(port, payload)| build_script::Entry {
                ports: vec![port],
                payload: payload.to_vec(),
            }),
    );
    let mut expected: BTreeMap<u16, Vec<Vec<u8>>> = BTreeMap::new();
    for entry in entries {
        for port in entry.ports {
            let variants = expected.entry(port).or_default();
            if !variants.contains(&entry.payload) {
                variants.push(entry.payload.clone());
            }
        }
    }
    for port in 0..=u16::MAX {
        let variants: Vec<&[u8]> = expected
            .get(&port)
            .into_iter()
            .flatten()
            .map(Vec::as_slice)
            .collect();
        assert_eq!(payloads_for(port), variants, "udp/{port}");
    }
}

