#[test]
fn malformed_service_probes_fail_with_source_lines() {
    for record in [
        "Probe UDP Missing",
        "Probe SCTP Wrong q||",
        "Probe UDP Missing q|end",
        r"Probe UDP Bad q|\x0g|",
        r"Probe UDP Short q|\x0|",
        r"Probe UDP Unknown q|\a|",
        "Probe UDP Wrong p|body|",
    ] {
        let error = build_script::parse_service_probes(&format!("# header\n{record}")).unwrap_err();
        assert!(error.starts_with("line 2:"), "{}", error);
    }
    for ports in ["65536", "2-1", "1,bogus", ""] {
        let error =
            build_script::parse_service_probes(&format!("Probe UDP Test q||\nports {ports}"))
                .unwrap_err();
        assert!(error.starts_with("line 2:"), "{}", error);
    }
}

